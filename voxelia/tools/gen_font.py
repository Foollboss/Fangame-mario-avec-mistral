ACCENTS = {
    'acute': ['...#.', '..#..'],
    'grave': ['.#...', '..#..'],
    'circ': ['..#..', '.#.#.'],
    'diaer': ['.#.#.', '.....'],
}


def accented(ch, base, accent, upper=False):
    rows, _ = G[base]
    w = len(rows[0])
    acc = [r[:w].ljust(w, '.') for r in ACCENTS[accent]]
    if w < 5:
        acc = [r[1:1 + w] for r in ACCENTS[accent]]
    if upper:
        G[ch] = (acc + rows, -2)
    else:
        G[ch] = (acc + rows[2:], 0)


