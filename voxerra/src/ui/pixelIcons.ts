export type PixelIconName = keyof typeof ICONS;

const NS = 'http://www.w3.org/2000/svg';

/** Chemin SVG des pixels pleins d'une grille, décalé de (ox, oy). */
function pixels(rows: readonly string[], ox: number, oy: number): string {
  let d = '';
  rows.forEach((row, y) => {
    // regroupe les pixels consécutifs d'une ligne en un seul rectangle
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let e = x;
      while (e < row.length && row[e] === '#') e++;
      d += `M${x + ox} ${y + oy}h${e - x}v1h${x - e}z`;
      x = e;
    }
  });
  return d;
}

/** Icône SVG (classe « px-icon », couleur = couleur du texte). */
export function pixelIcon(name: PixelIconName, cls = ''): SVGSVGElement {
  const rows = ICONS[name];
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${rows[0].length + 1} ${rows.length + 1}`);
  svg.setAttribute('shape-rendering', 'crispEdges');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', `px-icon ${cls}`.trim());
  const shadow = document.createElementNS(NS, 'path');
  shadow.setAttribute('d', pixels(rows, 1, 1));
  shadow.setAttribute('fill', 'rgba(0,0,0,0.55)');
  const main = document.createElementNS(NS, 'path');
  main.setAttribute('d', pixels(rows, 0, 0));
  main.setAttribute('fill', 'currentColor');
  svg.append(shadow, main);
  return svg;
}

